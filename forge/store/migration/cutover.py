"""Restartable one-way activation, owned by the CLI maintenance protocol.

Before selection, legacy admission is paused and every worker must finish verified
cleanup. After selection, resume can only finish the SQLite restart; it never
restores JSON as an authority. The sealed source copy is diagnostic evidence.
"""
import json
import os
from pathlib import Path
import time
import uuid

from ...state import _atomic_json as atomic_json
from ...legacy_writers import exclusive
from ..configuration import Configuration
from ..db import Store, _fsync_directory, _new_file, qualified_sqlite
from .importer import Importer, importer_version
from .snapshot import MigrationError, Snapshot, capture, decode, digest, encode, operation_lock, read_regular, sources, uncleaned_auxiliary, initial_setup, legacy_ledger
from .source import source_files

STAGES = {'draining','stopping','capturing','importing','validated','selected','complete','source_preparing'}


def maintenance_writable(root):
    """Public mutation guard; the CLI alone advances the maintenance journal."""
    root=Path(root).absolute()
    if root.name=='setup': root=root.parent
    path=root/'.migration-cutover.json'
    if path.exists():
        value=decode(read_regular(path,limit=1048576))
        if value.get('stage')!='complete':
            raise MigrationError('cutover_maintenance_in_progress')


def package_version(source):
    directory=Path(source)/'forge'
    paths=source_files(directory)
    return '1:'+digest(b''.join(path.relative_to(directory).as_posix().encode()+read_regular(path) for path in paths))


class Cutover:
    def __init__(self,host,*,clock=time.time,public_parity=None,qualify=None,after_stage=None):
        self.host,self.clock=host,clock
        self.root=host.root
        self.path=self.root/'.migration-cutover.json'
        self.marker=self.root/'state/storage'
        self.public_parity,self.qualify,self.after_stage=public_parity,qualify,after_stage

    def _read(self):
        value=decode(read_regular(self.path,limit=1048576))
        if (value.get('protocol')!=1 or value.get('root')!=str(self.root) or value.get('source')!=str(self.host.source)
                or value.get('stage') not in STAGES or not isinstance(value.get('services'),list)
                or value.get('authorized') is not True):
            raise MigrationError('invalid_cutover_journal')
        # Journal paths are generated by this protocol, never caller commands.
        identifier=value.get('id','')
        try: uuid.UUID(identifier)
        except (TypeError,ValueError): raise MigrationError('invalid_cutover_journal') from None
        if (value.get('snapshot')!=str(self.root.parent/('forge-pre-sqlite-'+identifier))
                or value.get('destination')!=str(self.root/'sqlite')):
            raise MigrationError('invalid_cutover_journal')
        import re
        if any(not isinstance(unit,str) or not re.fullmatch(r'forge[-a-z0-9]*\.(service|timer)',unit) for unit in value['services']):
            raise MigrationError('invalid_cutover_journal')
        return value

    def _save(self,value,stage=None,**fields):
        value.update(fields,updated_at=self.clock())
        if stage: value['stage']=stage
        atomic_json(self.path,value)
        if self.after_stage and stage: self.after_stage(stage)

    def _source_current(self,value):
        bridge=value.get('initial_source')
        if bridge and value['stage'] in {'stopping','capturing','source_preparing'}:
            allowed={bridge['from_revision']} if value['stage']!='source_preparing' else {bridge['from_revision'],bridge['to_revision']}
            if self.host.identity() not in allowed:
                raise MigrationError('cutover_source_changed')
            return
        if self.host.identity()!=value['source_revision'] or package_version(self.host.source)!=value['tool_version']:
            raise MigrationError('cutover_source_changed')

    def _runtime_current(self,value):
        if value.get('initial_source'):
            if not value['initial_runtime_frozen']:
                return
            path=self.root/'runtime.json'
            actual=digest(read_regular(path,limit=65536)) if path.exists() else None
            if actual!=value['initial_runtime_digest']:
                raise MigrationError('cutover_runtime_changed')
            return
        actual=read_regular(self.root/'runtime.json',limit=65536)
        if digest(encode(decode(actual)))!=value['paused_digest']:
            raise MigrationError('cutover_runtime_changed')

    def _pending(self):
        data=sources(self.root)
        ledger=legacy_ledger(data)
        return dict(pipeline=sum(not j['cleanup'] for j in ledger['jobs'].values()),
                    slots=len(ledger['slots']),auxiliary=uncleaned_auxiliary(data))

    def activate(self,*,expected_plan=None,source_revision=None,previous_revision=None,source_pack=None):
        with operation_lock(self.root,'.migration-host.lock'):
            if self.path.exists():
                return self._resume(self._read())
            if os.path.lexists(self.marker):
                raise MigrationError('runtime_already_selected')
            if self.host.journal.exists():
                raise MigrationError('maintenance_resume_required')
            plan=self.host.inspect()
            if expected_plan is not None and plan['plan']!=expected_plan:
                raise MigrationError('plan_changed')
            if previous_revision is not None and plan['source_revision']!=previous_revision:
                raise MigrationError('initial_source_changed')
            data=sources(self.root)
            initial=initial_setup(data)
            if source_revision is not None and not initial:
                raise MigrationError('initial_source_requires_never_started_setup')
            if initial and source_revision is None:
                raise MigrationError('initial_source_revision_required')
            setup=decode(data.get('state/onboarding/setup.json',b'{}'))
            if not initial and (setup.get('operation') or 'state/factory-paused.json' in data or setup and setup.get('phase')!='active'):
                raise MigrationError('cutover_setup_operation_pending')
            if set(plan['blockers'])-{'uncleaned_jobs'}:
                raise MigrationError('cutover_has_unmanaged_writers')
            if not qualified_sqlite():
                raise MigrationError('sqlite_unqualified')
            tool_version=importer_version()
            if initial:
                import re
                if not isinstance(source_revision,str) or not re.fullmatch(r'[a-f0-9]{40}',source_revision):
                    raise MigrationError('initial_source_revision_required')
                if source_revision!=plan['source_revision']:
                    if source_pack is None:
                        raise MigrationError('initial_source_pack_required')
                    self.host.prepare_source_update(plan['source_revision'],source_revision,tool_version,source_pack=source_pack)
                elif package_version(self.host.source)!=tool_version:
                    raise MigrationError('cutover_code_mismatch')
            elif package_version(self.host.source)!=tool_version:
                raise MigrationError('cutover_code_mismatch')
            destination=self.root/'sqlite'
            if os.path.lexists(destination):
                raise MigrationError('cutover_destination_exists')
            from ...settings import Settings
            from ...factory.config import load
            with Settings(self.root).locked('runtime-config'):
                original=None if initial else load(self.root)
                paused={**(original or {}),'enabled':False,'merge_enabled':False}
                identifier=str(uuid.uuid4())
                value=dict(protocol=1,id=identifier,authorized=True,actor_id="operator:cli:"+str(os.getuid()),root=str(self.root),source=str(self.host.source),
                    source_revision=plan['source_revision'],tool_version=tool_version,services=plan['services'],stage='draining',
                    original_runtime=original,paused_digest=digest(encode(paused)),started_at=self.clock(),updated_at=self.clock(),
                    snapshot=str(self.root.parent/('forge-pre-sqlite-'+identifier)),destination=str(destination))
                # The journal is durable before admission changes. Resume can
                # complete this write if the process dies in the following gap.
                if initial:
                    value.update(stage='stopping',initial_source=dict(from_revision=plan['source_revision'],to_revision=source_revision,prepared=None),
                                 initial_runtime_digest=None,initial_runtime_frozen=False)
                self._save(value)
                if not initial:
                    atomic_json(self.root/'runtime.json',paused)
            return self._resume(value)

    def resume(self, *, accept_tool_update=False, source_revision=None):
        with operation_lock(self.root,'.migration-host.lock'):
            if not self.path.exists():
                raise MigrationError('cutover_not_started')
            value=self._read()
            if accept_tool_update or value.get('tool_update'):
                self._update_tool(value, requested_revision=source_revision, authorize=accept_tool_update)
            elif source_revision:
                raise MigrationError('repair_authorization_required')
            return self._resume(value)

    def _update_tool(self, value, *, requested_revision, authorize):
        """Explicit forward repair of an unselected import, retaining every input."""
        import re
        from ...factory.control import controller_lock
        if os.path.lexists(self.marker) or value['stage'] in {'selected','complete'}:
            raise MigrationError('repair_after_selection_forbidden')
        if value.get('initial_source'):
            raise MigrationError('initial_setup_release_repair_not_supported')
        if value['stage'] not in {'importing','validated'}:
            raise MigrationError('repair_requires_frozen_snapshot')
        if os.path.lexists(self.root/'state'/('.pending-storage-'+value['id'])):
            raise MigrationError('repair_selection_pending')
        pending=value.get('tool_update')
        if pending is None and not authorize:
            raise MigrationError('repair_authorization_required')
        target=requested_revision or (pending or {}).get('to_revision')
        if not isinstance(target,str) or not re.fullmatch(r'[0-9a-f]{40}',target):
            raise MigrationError('repair_revision_required')
        version=importer_version()
        with controller_lock(self.root,timeout=10), exclusive(self.root):
            self.host.quiet()
            self._runtime_current(value)
            snapshot=Snapshot(value['snapshot'])
            if snapshot.id!=value['manifest']:
                raise MigrationError('cutover_snapshot_identity_changed')
            self._same_snapshot(snapshot)
            if any(self._pending().values()):
                raise MigrationError('cutover_drain_not_complete')
            destination=Path(value['destination'])
            if pending is None:
                history=value.get('source_updates',[])
                if len(history)>=20:
                    raise MigrationError('repair_history_limit')
                self.host.prepare_source_update(value['source_revision'],target,version)
                if target==value['source_revision'] and version==value['tool_version']:
                    raise MigrationError('repair_tool_unchanged')
                identifier=str(uuid.uuid4())
                exists=os.path.lexists(destination)
                if exists and (destination.is_symlink() or not destination.is_dir()):
                    raise MigrationError('repair_staging_unsafe')
                info=destination.stat() if exists else None
                pending=dict(id=identifier,from_revision=value['source_revision'],from_tool_version=value['tool_version'],
                    to_revision=target,to_tool_version=version,source_manifest=snapshot.id,
                    archive=str(destination.with_name('sqlite.diagnostic-'+identifier)),
                    staging_identity=[info.st_dev,info.st_ino] if info else None,
                    accepted_at=self.clock(),actor_id='operator:cli:'+str(os.getuid()),phase='prepared')
                self._save(value,tool_update=pending)
                if self.after_stage:self.after_stage('tool_update_prepared')
            if (pending.get('to_revision')!=target or pending.get('to_tool_version')!=version
                    or pending.get('from_revision')!=value['source_revision'] or pending.get('from_tool_version')!=value['tool_version']
                    or pending.get('source_manifest')!=snapshot.id or pending.get('phase') not in {'prepared','archived'}):
                raise MigrationError('repair_authority_mismatch')
            try:
                if str(uuid.UUID(pending['id']))!=pending['id']:raise ValueError()
            except (ValueError,KeyError,TypeError):raise MigrationError('repair_authority_mismatch') from None
            archive=destination.with_name('sqlite.diagnostic-'+pending['id'])
            if pending.get('archive')!=str(archive):
                raise MigrationError('repair_authority_mismatch')
            self.host.install_source_update(pending['from_revision'],target)
            if package_version(self.host.source)!=version:
                raise MigrationError('repair_bundle_source_mismatch')
            self._qualify(value)
            self.host.quiet()
            self._same_snapshot(snapshot)
            identity=pending.get('staging_identity')
            if identity is not None:
                if os.path.lexists(archive):
                    if os.path.lexists(destination):raise MigrationError('repair_staging_conflict')
                    retained=archive
                else:
                    retained=destination
                if (retained.is_symlink() or not retained.is_dir()
                        or [retained.stat().st_dev,retained.stat().st_ino]!=identity):
                    raise MigrationError('repair_staging_changed')
                if retained==destination:
                    os.rename(destination,archive)
                    _fsync_directory(destination.parent)
                    if self.after_stage:self.after_stage('tool_update_renamed')
            elif os.path.lexists(destination) or os.path.lexists(archive):
                raise MigrationError('repair_staging_conflict')
            pending['phase']='archived'
            self._save(value,tool_update=pending)
            if self.after_stage:self.after_stage('tool_update_archived')
            receipt={**pending,'completed_at':self.clock()}
            self._save(value,'importing',source_revision=target,tool_version=version,tool_update=None,
                source_updates=[*value.get('source_updates',[]),receipt],public_parity=None,qualification=None,normalized_parity=None)

    def status(self):
        value=self._read()
        result=dict(status=value['stage'],activation=os.path.lexists(self.marker),source_revision=value['source_revision'],
                    diagnostic_copy=value['snapshot'],database_root=value['destination'],
                    tool_update_pending=bool(value.get('tool_update')),source_updates=value.get('source_updates',[]))
        if result['activation']:
            from ..runtime import selected
            store=selected(self.root)
            result.update(status='active',storage='sqlite',instance_id=store.instance_id,rollback_supported=False)
        return result

    def _qualify(self,value):
        if self.qualify:
            proof=self.qualify(self.root,self.host.source)
        else:
            from ...host_update import qualify_sqlite_services
            proof=qualify_sqlite_services(self.root,self.host.source)
        if not isinstance(proof,dict) or proof.get('qualified') is not True:
            raise MigrationError('sqlite_service_runtime_unqualified')
        return proof

    def _public(self,snapshot,store):
        if self.public_parity:
            report=self.public_parity(snapshot,store)
        else:
            from .public_parity import verify
            report=verify(snapshot,store)
        if not isinstance(report,dict) or report.get('status')!='passed' or report.get('findings'):
            raise MigrationError('public_view_parity_failed')
        return report

    def _same_snapshot(self,snapshot):
        current=sources(self.root)
        if set(current)!=set(snapshot.entries) or any(digest(raw)!=snapshot.entries[name]['digest'] for name,raw in current.items()):
            raise MigrationError('cutover_source_state_changed')

    def _record(self,store,value,stage,**evidence):
        proof={'source_manifest':value.get('manifest'),'service_qualification':value.get('qualification'),
               'public_parity':value.get('public_parity'),'source_updates':value.get('source_updates',[]),
               'initial_source':value.get('initial_source'),**evidence}
        with store.write() as db:
            db.execute("INSERT INTO runtime_operations(id,kind,stage,source_revision,manifest_digest,started_at,updated_at,evidence_json) VALUES(?,'activate',?,?,?,?,?,?) "
                'ON CONFLICT(id) DO UPDATE SET stage=excluded.stage,updated_at=excluded.updated_at,evidence_json=excluded.evidence_json',
                (value['id'],stage,value['source_revision'],value['manifest'],value['started_at'],self.clock(),encode(proof).decode()))

    def _publish(self,value,store):
        content=('forge-sqlite-v1\n'+str(store.root)+'\n'+store.instance_id+'\n').encode()
        pending=self.root/'state'/('.pending-storage-'+value['id'])
        if os.path.lexists(self.marker):
            # Crash after link and before unlink: remove only our own duplicate.
            if pending.exists() and pending.stat().st_ino==self.marker.stat().st_ino:
                pending.unlink(); _fsync_directory(pending.parent)
            if read_regular(self.marker,limit=4096)!=content:
                raise MigrationError('runtime_selection_conflict')
            return
        if pending.exists():
            if read_regular(pending,limit=4096)!=content: raise MigrationError('runtime_selection_conflict')
        else: _new_file(pending,content)
        # Hard-link publication is atomic and cannot overwrite an existing marker.
        os.link(pending,self.marker,follow_symlinks=False)
        pending.unlink(); _fsync_directory(self.marker.parent)

    def _restart(self,value,store):
        self._qualify(value)
        self._publish(value,store)
        from ..runtime import selected
        if selected(self.root).instance_id!=store.instance_id:
            raise MigrationError('runtime_selection_conflict')
        if value.get('initial_source'):
            self.host.initial_updater('commit_initial',value,value['initial_source']['prepared'])
        if value['services']:
            self.host.command('systemctl','--user','start',*value['services'])
        if not set(value['services']).issubset(set(self.host.units())):
            raise MigrationError('sqlite_service_restart_incomplete')
        self._record(store,value,'complete',selection='sqlite',services=value['services'])
        self._save(value,'complete')
        with store.read_snapshot() as db:
            held=db.execute("SELECT COUNT(*) FROM unit_gates WHERE code='legacy_reconciliation' AND resolved_at IS NULL").fetchone()[0]
        return dict(status='active',activation=True,storage='sqlite',instance_id=store.instance_id,
            diagnostic_copy=value['snapshot'],database_root=value['destination'],services=value['services'],
            reconciliation_holds=held,source_manifest=value['manifest'],rollback_supported=False)

    def _resume(self,value):
        if value['stage']=='complete' or os.path.lexists(self.marker):
            store=Store.open(value['destination'])
            return self._restart(value,store)
        self._source_current(value)
        if value['stage']=='draining':
            # Stop public mutation entrypoints while the supervisor alone drains.
            public_services=[unit for unit in value['services'] if unit.startswith(('forge-status.','forge-ui.'))]
            if public_services: self.host.command('systemctl','--user','stop',*public_services)
            from ...settings import Settings
            with Settings(self.root).locked('runtime-config'):
                current=decode(read_regular(self.root/'runtime.json',limit=65536))
                if current==value['original_runtime']:
                    atomic_json(self.root/'runtime.json',{**current,'enabled':False,'merge_enabled':False})
                self._runtime_current(value)
            pending=self._pending()
            if any(pending.values()):
                return dict(status='draining',activation=False,pending=pending,next_command='forge migrate resume',
                    message='New pipeline work is paused. Existing workers must finish verified cleanup before activation.')
            self._save(value,'stopping')
        # Reissuing stop is safe after a lost response; the original service set
        # remains pinned in the journal rather than rediscovered after the stop.
        if value['services']:
            self.host.command('systemctl','--user','stop',*value['services'])
        self.host.quiet()
        from ...factory.control import controller_lock
        with controller_lock(self.root,timeout=10), exclusive(self.root):
            self._runtime_current(value)
            self.host.quiet()
            if any(self._pending().values()):
                raise MigrationError('cutover_drain_not_complete')
            current=sources(self.root)
            setup=decode(current.get('state/onboarding/setup.json',b'{}'))
            if value.get('initial_source'):
                if not initial_setup(current):
                    raise MigrationError('initial_setup_changed')
                if not value['initial_runtime_frozen']:
                    from ...factory.config import load
                    self._save(value,original_runtime=load(self.root),initial_runtime_frozen=True,
                               initial_runtime_digest=digest(current['runtime.json']) if 'runtime.json' in current else None)
            elif setup.get('operation') or 'state/factory-paused.json' in current or setup and setup.get('phase')!='active':
                raise MigrationError('cutover_setup_operation_pending')
            snapshot_path=Path(value['snapshot'])
            if value['stage'] in {'stopping','capturing'}:
                self._save(value,'capturing')
                if not snapshot_path.exists():
                    snapshot=capture(self.root,snapshot_path,source_revision=value['source_revision'],storage_generation=1,quiescent=self.host.quiet)
                else:
                    if not (snapshot_path/'sealed').exists():
                        # An interrupted copy has no authority. Keep its bytes
                        # separately, then capture a new sealed snapshot under
                        # the same still-held writer barrier.
                        if snapshot_path.is_symlink() or not snapshot_path.is_dir():
                            raise MigrationError('unsafe_incomplete_capture')
                        retained=snapshot_path.with_name(snapshot_path.name+'.incomplete-'+uuid.uuid4().hex)
                        os.rename(snapshot_path,retained); _fsync_directory(snapshot_path.parent)
                        snapshot=capture(self.root,snapshot_path,source_revision=value['source_revision'],storage_generation=1,quiescent=self.host.quiet)
                    else: snapshot=Snapshot(snapshot_path)
                self._same_snapshot(snapshot)
                self._save(value,'source_preparing' if value.get('initial_source') else 'importing',manifest=snapshot.id)
            snapshot=Snapshot(snapshot_path)
            if snapshot.id!=value['manifest']:
                raise MigrationError('cutover_snapshot_identity_changed')
            self._same_snapshot(snapshot)
            if value['stage']=='source_preparing':
                bridge=value['initial_source']
                self.host.install_source_update(bridge['from_revision'],bridge['to_revision'])
                if package_version(self.host.source)!=value['tool_version']:
                    raise MigrationError('repair_bundle_source_mismatch')
                self._save(value,source_revision=bridge['to_revision'])
                receipt=self.host.initial_updater('prepare_initial',value)
                self.host.quiet()
                self._same_snapshot(snapshot)
                self._save(value,'importing',initial_source={**bridge,'prepared':receipt})
            importer=Importer(snapshot,value['destination'])
            store=importer.store
            if value['stage']=='importing':
                report=importer.run()
                with store.read_snapshot() as db:
                    blocking=db.execute('SELECT subject,code FROM import_findings WHERE blocking=1').fetchall()
                    for finding in blocking:
                        if finding['code']=='truncated_observation':
                            preserved=db.execute("SELECT 1 FROM issues i JOIN issue_revisions r ON r.id=i.current_revision_id WHERE i.id=? AND json_extract(r.requirements_json,'$.body_truncated')=1",(finding['subject'],)).fetchone()
                            ungated=db.execute("SELECT 1 FROM unit_issues m JOIN units u ON u.id=m.unit_id WHERE m.issue_id=? AND m.left_at IS NULL AND u.state NOT IN ('merged','closed','dissolved') AND NOT EXISTS(SELECT 1 FROM unit_gates g WHERE g.unit_id=u.id AND g.code='legacy_reconciliation' AND g.resolved_at IS NULL)",(finding['subject'],)).fetchone()
                            if preserved and not ungated:continue
                        if finding['code']!='live_unit_requires_reconciliation' or not db.execute(
                                "SELECT 1 FROM unit_gates WHERE code='legacy_reconciliation' AND resolved_at IS NULL AND json_extract(details_json,'$.issue_key')=?",(finding['subject'],)).fetchone():
                            raise MigrationError('cutover_import_findings')
                public=self._public(snapshot,store)
                qualified=self._qualify(value)
                self._save(value,'validated',public_parity=public,qualification=qualified,normalized_parity=report['source_parity_mismatches'])
                self._record(store,value,'validated')
            self._qualify(value)
            # The private staging database is the sole object changed here. No
            # selected reader can see its restored intent until marker publication.
            with store.write() as db:
                if db.execute('PRAGMA integrity_check').fetchone()[0]!='ok' or db.execute('PRAGMA foreign_key_check').fetchone():
                    raise MigrationError('cutover_integrity_failed')
                db.execute("UPDATE store_metadata SET value='false' WHERE key='import_only'")
                for key,item in (('runtime_active','true'),('runtime_root',str(self.root))):
                    db.execute('INSERT INTO store_metadata(key,value) VALUES(?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value',(key,item))
                authority=dict(operation_id=value['id'],source_manifest=value['manifest'],actor_id=value.get('actor_id','operator:cli:'+str(os.getuid())))
                db.execute("INSERT INTO store_metadata(key,value) VALUES('migration_reconciliation_authorization',?) ON CONFLICT(key) DO UPDATE SET value=excluded.value",(json.dumps(authority,sort_keys=True),))
                row=db.execute("SELECT revision,settings_json FROM configuration WHERE domain='runtime.json' AND subject='instance' AND active=1").fetchone()
                if row is None or json.loads(row['settings_json'])!=value['original_runtime']:
                    Configuration(store,clock=self.clock).replace_in(db,'runtime.json',value['original_runtime'],expected_revision=row['revision'] if row else 0)
                db.execute("UPDATE import_runs SET status='validated',updated_at=? WHERE id=?",(self.clock(),value['manifest']))
            self._record(store,value,'selected',runtime_intent_restored=True)
            self._publish(value,store)
            self._save(value,'selected')
        return self._restart(value,store)
