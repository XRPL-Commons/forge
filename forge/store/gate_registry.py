"""Generate SQL and browser types from the gate authority registry."""
import argparse
import json
from pathlib import Path

from .codes import GATES, GATE_CLASSES

START='-- BEGIN GENERATED GATE REGISTRY\n'
END='-- END GENERATED GATE REGISTRY\n'


def sql():
    rows=[]
    for code,gate in GATES.items():
        values={'kind':gate.kind,'priority':gate.priority,'release':gate.release,
                'unit_scope':int('unit' in gate.scopes),'member_scope':int('member' in gate.scopes),
                'candidate_scope':int('candidate' in gate.scopes),'job_scope':int('job' in gate.scopes),
                'owner':gate.owner,'public_status':gate.public_status}
        literal=lambda value: str(value) if type(value) is int else "'"+value.replace("'","''")+"'"
        rows.append('UPDATE gate_codes SET '+','.join(key+'='+literal(value) for key,value in values.items())+
                    ' WHERE code='+literal(code)+';')
    return START+'\n'.join(rows)+'\n'+END


def typescript():
    values={code:{'class':gate.kind,'owner':gate.owner,'release':gate.release,
                  'scopes':sorted(gate.scopes),'status':gate.public_status} for code,gate in GATES.items()}
    return ('// Generated by python -m forge.store.gate_registry; edit forge/store/codes.py.\n'
            'export const gateRegistry = '+json.dumps(values,indent=2)+' as const\n\n'
            'export type GateCode = keyof typeof gateRegistry\n'
            'export type GateClass = '+ ' | '.join(repr(kind) for kind in GATE_CLASSES)+'\n'
            'export function gateDescriptor(code: string | null | undefined) {\n'
            '  return code && Object.hasOwn(gateRegistry, code) ? gateRegistry[code as GateCode] : null\n'
            '}\n')


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    root=Path(__file__).resolve().parents[2]
    migration=root/'forge/store/schema/004_consolidation.sql'
    browser=root/'ui/app/utils/gates.ts'
    current=migration.read_text()
    before,body=current.split(START,1);_,after=body.split(END,1)
    expected=before+sql()+after
    if args.check:
        if current!=expected or not browser.exists() or browser.read_text()!=typescript():
            parser.exit(1,'Gate registry outputs are stale; run python -m forge.store.gate_registry.\n')
    else:
        migration.write_text(expected);browser.write_text(typescript())


if __name__=='__main__':main()
