def access_call(operation, *args):
    try:
        return operation(*args)
    except AccessError as error:
        if error.status in (401, 403):
            raise MirrorError('installation_access_missing') from None
        if error.status == 404:
            raise MirrorError('repository_unavailable') from None
        raise MirrorError('mirror_unavailable', transient=True) from None


def denied_repositories(settings, repository_id):
    matches = [row for row in settings.load()['repositories'] if row['id'] == repository_id]
    if len(matches) != 1:
        raise MirrorError('repository_unavailable')
    return deepcopy(matches[0].get('mirror_denied_repositories', []))


def session_directory(root, session_id):
    # Session IDs are generated by the store, never taken from a request path.
    if str(uuid.UUID(session_id)) != session_id:
        raise MirrorError('session_invalid')
    return Path(root) / 'state/mirror-sockets' / uuid.UUID(session_id).hex


@dataclass(frozen=True)
class PreparedSource:
    input_directory: Path
    source_input: dict
    session_id: str
    socket_directory: Path
    network_generation: str
    publication_authorization: dict


class SourcePreparation:
    def __init__(self, root, store, *, github=None, access=None, git_store=None, settings=None, clock=time.time):
        self.root, self.store, self.clock = Path(root), store, clock
        self.settings = settings or Settings(root)
        self.access = access or MirrorAccess(self.settings)
        self.git_store = git_store or GitStore(self.root / 'state/factory/mirror/cache', credentials=self.access.credentials)
        self.mirror = MirrorStore(store, clock=clock)
        self.github = github

    def _directory(self, job_id):
        return self.root / 'state/factory/mirror/inputs' / hashlib.sha256(job_id.encode()).hexdigest()

    def _materialize(self, record):
        path = self._directory(record['job_id'])
        payload = source_inputs.encoded(source_inputs.assignment(record['source_input'], record['notes'],
                    manifest=self.mirror.authority(record['job_id'])['manifest'])) + b'\n'
        path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
        try:
            path.mkdir(mode=0o700)
        except FileExistsError:
            if path.is_symlink():
                raise MirrorError('source_artifact_invalid')
        target = path / 'assignment.json'
        try:
            descriptor = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o444)
        except FileExistsError:
            if target.is_symlink() or target.read_bytes() != payload:
                raise MirrorError('source_artifact_invalid') from None
        else:
            with os.fdopen(descriptor, 'wb') as stream:
                stream.write(payload)
                stream.flush()
                os.fsync(stream.fileno())
        path.chmod(0o555)
        socket_directory = session_directory(self.root, record['session_id'])
        socket_directory.mkdir(mode=0o700, parents=True, exist_ok=True)
        return PreparedSource(path, record['source_input'], record['session_id'], socket_directory,
                              record['network_generation'], record['publication_authorization'])

    def _notes(self, job, notes, publication_authorization):
        result = deepcopy(notes)
        result['publication_authorization'] = deepcopy(publication_authorization)
        if job.get('role') == 'recovery':
            # Recovery diagnoses the failed assignment, including requirements
            # that have since changed or closed. Never refresh its authority.
            with self.store.read_snapshot() as db:
                row = db.execute('SELECT failed_job_id FROM recovery_assignments WHERE job_id=?', (job['id'],)).fetchone()
            frozen = self.mirror.prepared(row['failed_job_id']) if row else None
            if frozen:
                result['failed_assignment'] = dict(job_id=row['failed_job_id'], source_input=frozen['source_input'],
                    notes=frozen['notes'])
            else:
                result['failed_assignment'] = dict(job_id=row['failed_job_id'] if row else None,
                    issue_snapshots=[{key: member.get(key) for key in
                        ('issue_number', 'title', 'body', 'requirements_hash')} for member in job.get('members', [])],
                    comments_unavailable=True)
        elif self.github is not None and job.get('members'):
            observations = []
            for member in job['members']:
                item = dict(repo=job['repo'], repo_id=job['repo_id'], number=member['issue_number'])
                value, requirements, comments = self.github.issue_inputs(item)
                expected = member['requirements']
                if (isinstance(expected, str) and requirements != expected
                        or not isinstance(expected, str) and
                        (value['title'] != member['title'] or (value.get('body') or '') != member['body'])):
                    raise MirrorError('assignment_changed')
                observations.append(dict(number=value['number'], title=value['title'], body=value.get('body') or '',
                    requirements_hash=requirements, observed_at=self.clock(), comments=[
                        {key: comment.get(key) for key in ('id', 'body', 'created_at', 'updated_at')} |
                        {'author': (comment.get('user') or {}).get('login'), 'author_type': (comment.get('user') or {}).get('type')}
                        for comment in comments]))
            result['issue_observations'] = observations
        if len(source_inputs.encoded(result)) > source_inputs.MAX_NOTES_BYTES:
            raise MirrorError('source_notes_capacity')
        return result

    @staticmethod
    def _pins(job, manifest):
        original = (job.get('failure') or {}).get('input_manifest') if job.get('role') == 'recovery' else manifest
        original = original or manifest
        candidate = job.get('candidate') or {}
        base = original.get('base_oid') or candidate.get('base') or job.get('head')
        inputs = [value for value in (original.get('head_oid'), candidate.get('head'), job.get('resume_head')) if value is not None]
        for key in ('existing_candidates', 'part_outputs', 'prerequisite_outputs'):
            for item in original.get(key, []):
                oid = item.get('head_oid') or item.get('head') or item.get('commit_oid')
                if oid is not None:
                    inputs.append(oid)
        if base is not None and (not isinstance(base, str) or not OID.fullmatch(base)):
            raise MirrorError('revision_unavailable')
        if any(not isinstance(value, str) or not OID.fullmatch(value) for value in inputs):
            raise MirrorError('revision_unavailable')
        return base, sorted(set(inputs))

    def _source_pins(self, job, manifest):
        failed_id = (job.get('failure') or {}).get('attempt') if job.get('role') == 'recovery' else None
        frozen = self.mirror.prepared(failed_id) if failed_id else None
        if frozen:
            source = frozen['source_input']
            return source['base_oid'], list(source['input_oids'])
        return self._pins(job, manifest)

    def prepare(self, job, notes, *, publication_authorization=None, bundle_inputs=()):
        authority = self.mirror.authority(job['id'])
        if job.get('execution_fence', authority['execution_fence']) != authority['execution_fence']:
            raise MirrorError('assignment_changed')
        if job.get('repo_id') != authority['repo_id'] or canonical_name(job['repo']) != canonical_name(authority['repo']):
            raise MirrorError('assignment_changed')
        previous = self.mirror.prepared(job['id'])
        if previous:
            if previous['revoked_at'] is not None or previous['execution_fence'] != authority['execution_fence']:
                raise MirrorError('session_revoked')
            return self._materialize(previous)
        authorization = publication_authorization or {}
        try:
            repository = access_call(self.access.resolve, authority['repo'])
        except MirrorError as error:
            self.mirror.preparation_receipt(authority, dict(repository=canonical_name(authority['repo']),
                repository_id=authority['repo_id'], request_kind='prepare_assignment', outcome='failed' if error.transient else 'denied',
                reason=error.reason, transient=error.transient, finished_at=self.clock()))
            raise
        if repository.repository_id != authority['repo_id']:
            raise MirrorError('assignment_changed')
        organizations = access_call(self.access.organizations)
        denies = denied_repositories(self.settings, repository.repository_id)
        manifest = authority['manifest']
        policy = dict(version=1, project_repository_id=repository.repository_id,
            canonical_repository=canonical_name(repository.canonical_name), revision=source_inputs.digest(manifest),
            manifest_digest=source_inputs.digest(manifest), declared_repositories=[],
            organization_installations=organizations, denied_repositories=denies, extractor_version=1)
        try:
            authorize(policy, repository, live_installations=organizations, live_denied=denies)
        except MirrorError as error:
            self.mirror.preparation_receipt(authority, dict(repository=canonical_name(repository.canonical_name),
                repository_id=repository.repository_id, request_kind='prepare_assignment', outcome='denied',
                reason=error.reason, transient=error.transient, finished_at=self.clock()))
            raise
        if authority['domain'] == 'pipeline':
            from ..store.executions import ExecutionQueries
            trusted_job = ExecutionQueries(self.store).job(job['id'])
        else:
            trusted_job = authority['manifest']
        base, inputs = self._source_pins(trusted_job, manifest)
        # Bundles are retained output references supplied by ExecutionQueries;
        # their exact head is already pinned by the immutable parent assignment.
        bundles = list(bundle_inputs)
        bundle_heads = {reference['commit_oid'] for reference in bundles}
        if not bundle_heads.issubset(set(inputs)):
            raise MirrorError('assignment_changed')
        remote_pins = [oid for oid in [base, *inputs] if oid and oid not in bundle_heads]
        self._fetch(authority, repository, remote_pins)
        if base is None:
            base = run_git(['--git-dir', str(self.git_store.path(repository.repository_id)),
                            'rev-parse', 'HEAD^{commit}']).decode().strip()
        for reference in bundles:
            self.git_store.import_bundle(repository, reference['content'], reference['commit_oid'], base,
                [],
                alive=lambda: self._still_owned(authority))
        self._fetch(authority, repository, [base, *inputs])
        reader = self.git_store.reader(repository.repository_id)

        def nested(declaration):
            details = dict(repository=declaration['canonical_name'], request_kind='resolve_dependency',
                           started_at=self.clock())
            try:
                nested_repo = access_call(self.access.resolve, declaration['canonical_name'])
                details['repository_id'] = nested_repo.repository_id
                nested_policy = {**policy, 'declared_repositories': [declaration]}
                authorize(nested_policy, nested_repo, live_installations=organizations,
                          live_denied=denied_repositories(self.settings, repository.repository_id))
                selector = declaration['source_evidence'].get('dependency_ref')
                self._fetch(authority, nested_repo, [selector] if isinstance(selector, str) and OID.fullmatch(selector) else [])
                commit = resolve_revision(self.git_store, nested_repo, selector, alive=lambda: self._still_owned(authority))
                self._fetch(authority, nested_repo, [commit])
                return nested_repo.repository_id, nested_repo.canonical_name, self.git_store.reader(nested_repo.repository_id), commit
            except MirrorError as error:
                self.mirror.preparation_receipt(authority, {**details, 'outcome': 'failed' if error.transient else 'denied',
                    'reason': error.reason, 'transient': error.transient, 'finished_at': self.clock()})
                if error.transient or error.reason in {'session_revoked', 'mirror_capacity'}:
                    raise
                # The root declaration remains allowed (subject to its deny),
                # but inaccessible trees cannot invent additional dependencies.
                # Its exact refusal is already an actionable job claim.
                return None

        extraction = dependency_closure(reader, repository.repository_id, repository.canonical_name,
                                         [base, *inputs], resolve_pinned=nested)
        declared = extraction.repositories
        policy['declared_repositories'] = declared
        frozen_notes = self._notes(trusted_job, notes, authorization)
        if extraction.unsupported:
            frozen_notes['unsupported_dependency_declarations'] = extraction.unsupported
        source = source_inputs.create(repository_id=repository.repository_id, canonical_repository=repository.canonical_name,
            base_oid=base, input_oids=inputs, manifest=manifest, dependency_policy_digest=policy_digest(policy), notes=frozen_notes)
        self.mirror.admit(job['id'], source, policy, frozen_notes, authorization,
            execution_fence=authority['execution_fence'], network_generation=str(uuid.uuid4()), deadline=authority['deadline'])
        return self._materialize(self.mirror.prepared(job['id']))

    def _fetch(self, authority, repository, pins):
        details = dict(repository=canonical_name(repository.canonical_name), repository_id=repository.repository_id,
            request_kind='prepare', outcome='started', requested_oids=sorted(set(pins)), started_at=self.clock())
        self.mirror.preparation_receipt(authority, details)
        try:
            cache = self.git_store.ensure(repository, pinned_oids=pins, alive=lambda: self._still_owned(authority))
            self.mirror.preparation_receipt(authority, {**details, **cache, 'outcome': 'prepared', 'finished_at': self.clock()})
        except (MirrorError, AccessError) as error:
            reason = error.reason if isinstance(error, MirrorError) else 'installation_access_missing'
            transient = getattr(error, 'transient', False)
            self.mirror.preparation_receipt(authority, {**details, 'outcome': 'failed' if transient else 'denied',
                'reason': reason, 'transient': transient, 'finished_at': self.clock()})
            if isinstance(error, AccessError):
                raise MirrorError(reason) from None
            raise

    def _still_owned(self, authority):
        try:
            current = self.mirror.authority(authority['job_id'])
            return (current['execution_fence'] == authority['execution_fence']
                    and current['manifest'] == authority['manifest'])
        except MirrorError:
            return False
