import assert from 'node:assert/strict'

export default async function (page, { base, scenario, requests }) {
  await scenario('repository-settings')
  await page.goto(base + '/settings/repositories/2')
  await page.getByLabel('Merging', { exact: true }).waitFor()
  await page.waitForFunction(() => document.querySelector('#__nuxt')?.__vue_app__?.config.globalProperties.$nuxt?.isHydrating === false)
  assert.equal(await page.getByRole('button', { name: 'Review setup', exact: true }).count(), 0)
  assert.equal(await page.locator('#merge-policy').inputValue(), 'human')
  assert.equal(await page.locator('#review-scope').inputValue(), 'forge')
  assert.match(await page.locator('#review-scope-help').innerText(), /only the pull requests it creates/)
  assert.equal(await page.locator('#mirror-denied, #test-databases, #deployment').count(), 0, 'advanced sections mount only on demand')
  await page.locator('#merge-policy').selectOption('auto')
  assert.equal((await requests()).filter(r => r.method === 'POST' && r.path.endsWith('/merge-policy')).length, 0)
  await page.getByRole('button', { name: 'Save merging', exact: true }).click()
  await page.locator('form').filter({ has: page.locator('#merge-policy') }).getByRole('status').waitFor()
  const save = (await requests()).find(r => r.method === 'POST' && r.path.endsWith('/merge-policy'))
  assert.deepEqual(save.body, { repo_id: 2, revision: 'runtime-rev-1', mode: 'auto' })
  await page.reload()
  assert.equal(await page.locator('#merge-policy').inputValue(), 'auto')
  assert.equal(await page.locator('#review-scope').inputValue(), 'forge', 'saving merge policy preserves review scope')
  await page.locator('#review-scope').selectOption('all')
  await page.getByRole('button', { name: 'Save review pull requests', exact: true }).click()
  await page.locator('form').filter({ has: page.locator('#review-scope') }).getByRole('status').waitFor()
  assert.match(await page.locator('#review-scope-help').innerText(), /both its own/)
  await page.locator('#recovery-policy').selectOption('manual')
  await page.getByRole('button', { name: 'Save recovery', exact: true }).click()
  await page.locator('form').filter({ has: page.locator('#recovery-policy') }).getByRole('status').waitFor()
  await page.locator('summary').filter({ hasText: 'Deployment tracking' }).click()
  assert.equal(await page.locator('#deployment-domain, #deployment-confirm').count(), 0)
  assert.match(await page.locator('#deployment').innerText(), /no supported way to track/)
  await page.getByText('Inspection details', { exact: true }).click()
  assert.match(await page.locator('#deployment-sentence').innerText(), /belongs to another repository/)
  await page.locator('summary').filter({ hasText: 'Dependency access' }).click()
  await page.locator('#mirror-denied').fill('example/private')
  await page.locator('summary').filter({ hasText: 'Dependency access' }).click()
  await page.locator('summary').filter({ hasText: 'Dependency access' }).click()
  assert.equal(await page.locator('#mirror-denied').inputValue(), 'example/private', 'folding details preserves unsaved edits')
  await page.getByRole('switch', { name: 'Enable automation', exact: true }).click()
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'detached' })
  assert.equal((await requests()).filter(r => r.method === 'POST' && r.path.endsWith('/disable')).length, 0)
  await page.locator('summary').filter({ hasText: 'Dependency access' }).click()
  await page.locator('summary').filter({ hasText: 'Deployment tracking' }).click()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: '/private/tmp/forge-settings-desktop.png', fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: '/private/tmp/forge-settings-mobile.png', fullPage: true, animations: 'disabled' })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
}
