import assert from 'node:assert/strict'

export default async function (page, { base, scenario, requests }) {
  await page.goto(base + '/settings/agents')
  await page.getByText('Configure HTTPS and operator sign-in to connect an agent.').waitFor()
  assert.equal(await page.getByRole('button', { name: 'Review request' }).count(), 0)
  await scenario('auth-agents')
  await page.goto(base + '/settings/agents?code=BCDF-2345')
  await page.waitForURL(/\/login\?return_to=/)
  const signIn = await page.getByRole('link', { name: 'Continue with GitHub' }).getAttribute('href')
  assert.ok(signIn.includes('return_to=%2Fsettings%2Fagents%3Fcode%3DBCDF-2345'))
  await page.context().addCookies([{ name: 'synthetic_operator', value: 'yes', url: base }])
  await page.goto(base + '/settings/agents?code=BCDF-2345')
  assert.equal(await page.getByLabel('Connection code').inputValue(), 'BCDF-2345')
  await page.getByRole('button', { name: 'Review request' }).click()
  await page.getByRole('heading', { name: 'Local agent' }).waitFor()
  assert.equal(await page.getByRole('button', { name: 'Approve connection' }).isDisabled(), true)
  await page.getByRole('checkbox', { name: 'Enable or disable repository automation' }).uncheck()
  await page.getByRole('checkbox', { name: 'example/project (repository ID 321)' }).uncheck()
  await page.getByRole('checkbox', { name: 'I started this connection and the code matches my local client.' }).check()
  await page.getByRole('button', { name: 'Approve connection' }).click()
  await page.getByText('Connection approved. Return to your agent to finish connecting.').waitFor()
  await page.getByRole('button', { name: 'Revoke access' }).waitFor()
  const approval = (await requests()).find(r => r.path === '/api/connections/decide')
  assert.deepEqual(approval.body.capabilities, ['repositories:read', 'repositories:prepare'])
  assert.deepEqual(approval.body.scope, { repositories: [], owners: [{ id: 88, login: 'example' }] })
  assert.equal(approval.body.confirmed, true)
  await page.getByRole('button', { name: 'Revoke access' }).click()
  await page.getByRole('heading', { name: 'Local agent · revoked' }).waitFor()
  await page.getByLabel('Connection code').fill('ZZZZ-ZZZZ')
  await page.getByRole('button', { name: 'Review request' }).click()
  await page.getByText('This code expired or has already been used.').waitFor()
  await page.getByLabel('Connection code').fill('BCDF-2345')
  await page.getByRole('button', { name: 'Review request' }).click()
  await page.getByRole('button', { name: 'Deny', exact: true }).click()
  await page.getByText('Connection denied.', { exact: true }).waitFor()
}
