import assert from 'node:assert/strict'

const JOB = '44444444-4444-4444-8444-444444444670'
const OLD = '44444444-4444-4444-8444-444444444669'

export default async function (page, { base, scenario, requests }) {
  page.setDefaultTimeout(10000)
  page.setDefaultNavigationTimeout(10000)
  await scenario('pull-request-work')
  await page.goto(base + '/')
  const work = page.locator('#pull-request-work')
  await work.getByText('Correct the session loader', { exact: true }).waitFor()
  assert.match(await work.innerText(), /Review · Waiting to retry/)
  assert.match(await work.innerText(), /Review · Queued/)
  assert.match(await work.innerText(), /Dependency downloads are rate limited/)
  assert.equal((await requests()).some(r => r.path === '/api/factory/output'), false, 'board does not preload worker logs')
  assert.match(await work.innerText(), /2 shown/)
  assert.match(await work.innerText(), /Only recent completed reviews/)
  await work.getByRole('link', { name: 'View more active reviews' }).click()
  await page.getByRole('heading', { name: 'Active pull request reviews', exact: true }).waitFor()
  await page.getByText('Review beyond the initial Activity window', { exact: true }).waitFor()
  await page.getByRole('link', { name: 'First page', exact: true }).click()
  await page.getByRole('link', { name: 'Next page' }).waitFor()
  await page.goto(base + '/')
  await work.getByText('Correct the session loader', { exact: true }).click()
  await page.waitForURL('**/pull-requests/1/670')
  await page.locator('#pull-request-stage').waitFor()
  assert.match(await page.locator('#pull-request-status').innerText(), /Next automatic retry/)
  assert.match(await page.locator('#pull-request-status').innerText(), /Current revision aaaaaaaaaaaa/)
  assert.equal((await requests()).some(r => r.path === '/api/factory/output'), false, 'closed output stays lazy')
  await page.getByRole('button', { name: 'Worker output', exact: true }).click()
  await page.locator('#issue-output pre').waitFor()
  assert.match(await page.locator('#issue-output pre').innerText(), /HTTP 429/)
  await page.getByRole('button', { name: 'Load earlier attempts' }).click()
  const old = page.locator(`#issue-jobs a[href*="${OLD}"]`)
  await old.waitFor()
  assert.match(await old.innerText(), /earlier revision/)
  await old.click()
  await page.waitForURL(url => url.searchParams.get('job') === OLD, { timeout: 10000 })
  await page.waitForFunction(() => document.querySelector('#pull-selected-attempt')?.textContent.includes('historical attempt'))
  await page.reload()
  await page.waitForFunction(() => document.querySelector('#pull-selected-attempt')?.textContent.includes('historical attempt'))
  await page.locator('#issue-output pre').waitFor()
  assert.ok((await requests()).some(r => r.path === '/api/factory/output' && r.query.id === OLD), 'old direct link reads the historical job')
  assert.equal(await page.getByRole('button', { name: /Close issue|Retry issue|Stop attempt/ }).count(), 0, 'no issue-based controls')

  await page.goto('about:blank')
  await scenario('pull-request-running')
  await page.goto(base + '/pull-requests/1/670?job=' + JOB)
  await page.waitForFunction(() => document.querySelector('#pull-request-stage')?.textContent.includes('Audit · Running'))
  await page.locator('#issue-output-live').waitFor()
  assert.match(await page.locator('#pull-selected-attempt').innerText(), /This is the active worker/)
  await page.setViewportSize({ width: 320, height: 900 })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'PR detail fits a 320px viewport')
  assert.equal(await page.getByRole('link', { name: 'Forge home', exact: true }).count(), 1)
  assert.equal(await page.locator('h1').count(), 1)
  if (process.env.FORGE_E2E_PR_SCREENSHOT) await page.screenshot({ path: process.env.FORGE_E2E_PR_SCREENSHOT, fullPage: false })

  await page.goto('about:blank')
  await scenario('pull-request-completed')
  await page.goto(base + '/')
  await page.locator('#pull-request-work').getByText('Correct the session loader', { exact: true }).waitFor()
  assert.match(await page.locator('#pull-request-work').innerText(), /Merged on GitHub; remaining Forge work stopped/)
  await page.locator('#pull-request-work').getByText('Correct the session loader', { exact: true }).click()
  await page.waitForFunction(() => document.querySelector('#pull-request-stage')?.textContent.includes('Merged · Completed'))
  assert.match(await page.locator('#issue-jobs').innerText(), /Review · Deferred/)
}
